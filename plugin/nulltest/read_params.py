"""Reads the built plug-in's parameter list and writes params.md beside this script.

The reference is a feature of a DAW, so there is no reference plug-in whose
parameters a host tool could dump. The table is the list of Chan Sampler's own
parameters as a host sees them, printed by `CsRender params`: the ID, the
name, the kind, the steps, the default's text and the text at five points of
the normalised range. What each control does in FL and how it was measured is
in MEASUREMENTS.md.

    python read_params.py                 write params.md
    python read_params.py --check         exit 1 when params.md is not the build's list (ctest runs this)
    python read_params.py --tool <path>   another CsRender than build/'s

Standard library only.
"""
import argparse, os, subprocess, sys, textwrap

ROOT = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(ROOT, 'params.md')
COLUMNS = ('#', 'Parameter ID', 'Name in a host', 'Kind', 'Steps', 'Default', 'At 0', 'At 1/4', 'At 1/2', 'At 3/4', 'At 1')


def default_tool():
    repo = os.path.normpath(os.path.join(ROOT, '..', '..'))
    return os.path.join(repo, 'build', 'CsRender_artefacts', 'Release', 'CsRender' + ('.exe' if sys.platform == 'win32' else ''))


def cell(text):
    text = text.strip().replace('|', '\\|')
    return text if text else '(empty)'


def table(tool):
    done = subprocess.run([tool, 'params'], capture_output=True, timeout=120)
    if done.returncode != 0:
        raise SystemExit(f'{tool} params: exit {done.returncode}')
    rows = [line.split('\t') for line in done.stdout.decode('utf-8').replace('\r\n', '\n').split('\n') if line]
    if not rows or any(len(r) != len(COLUMNS) for r in rows):
        raise SystemExit(f'{tool} params: {len(rows)} lines, not all of {len(COLUMNS)} fields')
    kinds = {}
    for r in rows:
        kinds[r[3]] = kinds.get(r[3], 0) + 1
    counts = ', '.join(f'{n} {k}' for k, n in sorted(kinds.items(), key=lambda kv: (-kv[1], kv[0])))
    intro = ('Generated by `nulltest/read_params.py` from the built plug-in (`CsRender params`). Do not edit by hand: '
             'change `Source/Params.h`, build and run the script; ctest fails while this file is not the build\'s list.')
    body = (f'{len(rows)} parameters in the host\'s order: {counts}. Steps is 0 for a continuous parameter. The five '
            '"At" columns are the text the plug-in shows at that point of the normalised range, which is what a host '
            'automates. What each control does and how its law was measured is in '
            '[MEASUREMENTS.md](../MEASUREMENTS.md).')
    wrap = lambda s: textwrap.wrap(s, 118, break_long_words=False, break_on_hyphens=False)
    lines = [
        '# Chan Sampler: parameters',
        '',
        *wrap(intro),
        '',
        *wrap(body),
        '',
        '| ' + ' | '.join(COLUMNS) + ' |',
        '|' + '---|' * len(COLUMNS),
    ]
    for r in rows:
        r = [cell(c) for c in r]
        r[1] = f'`{r[1]}`'
        lines.append('| ' + ' | '.join(r) + ' |')
    return '\n'.join(lines) + '\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--check', action='store_true', help='compare instead of writing')
    ap.add_argument('--tool', default=default_tool(), help='the CsRender to ask')
    a = ap.parse_args()
    text = table(a.tool)
    if a.check:
        try:
            have = open(OUT, encoding='utf-8', newline='').read().replace('\r\n', '\n')
        except OSError:
            have = ''
        if have != text:
            print('params.md is not the list of the built plug-in: run nulltest/read_params.py')
            return 1
        print('params.md matches the built plug-in')
        return 0
    open(OUT, 'w', encoding='utf-8', newline='\n').write(text)
    print(f'wrote {os.path.relpath(OUT, ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())

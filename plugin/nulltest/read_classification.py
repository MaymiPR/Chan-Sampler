"""Reads the offline suite's saved results and writes classification.md beside this script.

One row per stage of the sound that the offline suite covers: its class, how
its law was found, and its reading on the scale, computed from the results
(ours/offline_results.json, written by nulltest.py). The class and the method
of a stage are set in STAGES below, from MEASUREMENTS.md; every number of the
sheet comes from the results file.

    python read_classification.py                    write classification.md
    python read_classification.py --results <file>   another results file

Run it after every full run of nulltest.py.
"""
import argparse, json, os, re, statistics, sys, textwrap, time

import ref_solo_lib as F

ROOT = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(ROOT, 'classification.md')
RESULTS = os.path.join(ROOT, 'ours', 'offline_results.json')

# (stage, the cases of the stage, class, how the law was found)
STAGES = [
    ('Default playback: velocity, output level, end of sample', r'off_base$', 'exact',
     'closed-form laws read from renders'),
    ('Boost and clip', r'off_boost', 'exact', 'a gain law and a hard clip read from renders'),
    ('EQ', r'off_eq', 'exact', 'a one-pole recursion read from renders'),
    ('Fade in and out', r'off_f(in|out)\d', 'exact', 'linear slopes relative to the sample length'),
    ('Sample start and length', r'off_(start|len|st)\d', 'exact', 'frame counts found in trims of noise'),
    ('Tools: normalize, reverse, polarity, swap, fade stereo, remove DC', r'off_(norm|rev|inv|swap|fadest|remdc)$', 'exact',
     'each does what its name says'),
    ('Trim', r'off_trim', 'exact', 'a threshold on the louder channel'),
    ('Ring modulation', r'off_rm', 'exact', 'a sine and a cosine at a rate read from renders'),
    ('Precomputed cut and resonance', r'offL_pccut', 'fittable',
     'a recursion; the resonance measured at points and fitted with a cubic'),
    ('Stereo delay', r'off_sd', 'exact', 'a delay of whole samples on one channel'),
    ('Pogo', r'off_pogo', 'exact', 'a time warp in closed form'),
    ('Start offset', r'off_so', 'exact', 'a fraction of the sample'),
    ('Declick in and out', r'off_dk', 'fittable', 'fade times read from renders; the crossfade curve a polynomial fit'),
    ('Crossfade loop', r'off_xf', 'exact', 'a linear blend over a length read from renders'),
    ('Envelope', r'off_env', 'fittable', 'times measured at six tempos; one constant fitted per tension'),
    ('Filter types', r'off_flt', 'fittable', 'coefficients from tables measured every 8 raw steps'),
]


def sheet(results, made):
    left = dict(results)
    rows = []
    for stage, pattern, cls, method in STAGES:
        cases = [(n, d) for n, d in results if re.match(pattern, n)]
        if not cases:
            raise SystemExit(f'no case of the results matches the stage "{stage}"')
        for n, _ in cases:
            if n not in left:
                raise SystemExit(f'the case {n} matches two stages')
            del left[n]
        worst = max(cases, key=lambda c: c[1])
        rows.append((stage, cls, method, len(cases), statistics.median(d for _, d in cases), worst, F.verdict(worst[1])))
    if left:
        raise SystemExit('cases with no stage: ' + ', '.join(sorted(left)))
    by_class = {}
    for r in rows:
        by_class[r[1]] = by_class.get(r[1], 0) + 1
    classes = ', '.join(f'{n} {c}' for c, n in sorted(by_class.items(), key=lambda kv: (-kv[1], kv[0])))
    not_null = [r[0] for r in rows if r[6] != 'NULL']
    wrap = lambda s: textwrap.wrap(s, 118, break_long_words=False, break_on_hyphens=False)
    lines = ['# Chan Sampler: classification sheet', '']
    lines += wrap('Generated by `nulltest/read_classification.py` from the offline suite\'s saved results. Do not edit by '
                  'hand: the class and the method of a stage are set in the script, from '
                  '[MEASUREMENTS.md](../MEASUREMENTS.md#measured-laws); the numbers are the results\'.') + ['']
    lines += wrap(f'{len(rows)} stages over {len(results)} offline cases, from the run of {made}: {classes}. '
                  f'The reading is the stage\'s worst case on the scale of '
                  f'[MEASUREMENTS.md](../MEASUREMENTS.md#setup). '
                  + (f'{len(not_null)} stages read below a NULL: ' + '; '.join(not_null) + '.' if not_null
                     else 'Every stage reads a NULL.')) + ['']
    lines += wrap('No target and no round budget were set per stage when the stages were fitted, so the sheet has '
                  'neither column. A stage with no offline case has no row: the time-stretch modes, which cannot null '
                  '(the reference\'s engine is proprietary) and are compared by behaviour, and the features tested only '
                  'as pairs inside the DAW, whose figures stand beside their laws in MEASUREMENTS.md.') + ['']
    lines += ['| Stage | Class | How the law was found | Cases | Median, dB | Worst case | Worst, dB | Reading |',
              '|---|---|---|---|---|---|---|---|']
    for stage, cls, method, n, median, worst, reading in rows:
        lines.append(f'| {stage} | {cls} | {method} | {n} | {median:.1f} | `{worst[0]}` | {worst[1]:.1f} | {reading} |')
    return '\n'.join(lines) + '\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--results', default=RESULTS, help='the results file (default ours/offline_results.json)')
    a = ap.parse_args()
    with open(a.results, encoding='utf-8') as h:
        results = [(n, float(d)) for n, d in json.load(h)]
    made = time.strftime('%Y-%m-%d', time.localtime(os.path.getmtime(a.results)))
    open(OUT, 'w', encoding='utf-8', newline='\n').write(sheet(results, made))
    print(f'wrote {os.path.relpath(OUT, ROOT)}: {len(STAGES)} stages, {len(results)} cases')
    return 0


if __name__ == '__main__':
    sys.exit(main())
